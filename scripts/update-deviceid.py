#!/usr/bin/env python3
"""Regenerates deviceid_data.go from the APRS device identification database
(https://github.com/aprsorg/aprs-deviceid, CC BY-SA 2.0, maintained by OH7LZB).

Usage: scripts/update-deviceid.py <path to a clone of aprsorg/aprs-deviceid>

Contact addresses are dropped; everything the library uses is kept as it is.
"""
import json, pathlib, subprocess, sys

import yaml

src = pathlib.Path(sys.argv[1])
db = yaml.safe_load((src / "tocalls.yaml").read_text(encoding="utf-8"))
commit = subprocess.run(["git", "-C", str(src), "log", "-1", "--format=%H %cs"],
                        capture_output=True, text=True, check=True).stdout.strip()


def s(v):
    # A Go string literal; JSON's escaping is valid Go for these texts.
    return json.dumps("" if v is None else str(v), ensure_ascii=False)


def features(e):
    f = e.get("features", [])
    return "nil" if not f else "[]string{" + ", ".join(s(x) for x in f) + "}"


def device(e):
    return f'Device{{Vendor: {s(e.get("vendor"))}, Model: {s(e.get("model"))}, Class: {s(e.get("class"))}, OS: {s(e.get("os"))}, Features: {features(e)}}}'


lines = [
    "// Code generated by scripts/update-deviceid.py from aprsorg/aprs-deviceid. DO NOT EDIT.",
    "// Source: https://github.com/aprsorg/aprs-deviceid, CC BY-SA 2.0, maintained by OH7LZB.",
    "",
    "package aprs",
    "",
    f"const deviceDatabaseVersion = {s(commit)}",
    "",
    "var tocalls = []tocallEntry{",
]
for t in db["tocalls"]:
    lines.append(f'\t{{{s(t["tocall"])}, {device(t)}}},')
lines += ["}", "", "var micESuffixes = []micESuffixEntry{"]
for m in db["mice"]:
    lines.append(f'\t{{{s(m["suffix"])}, {device(m)}}},')
lines += ["}", "", "var micELegacy = []micELegacyEntry{"]
for m in db["micelegacy"]:
    suffix = s(m["suffix"]) if "suffix" in m else '""'
    has = "true" if "suffix" in m else "false"
    lines.append(f'\t{{{s(m["prefix"])}, {suffix}, {has}, {device(m)}}},')
lines += ["}", ""]
dest = pathlib.Path(__file__).resolve().parent.parent / "deviceid_data.go"
dest.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {dest} ({len(db['tocalls'])} tocalls, {len(db['mice'])} mice, {len(db['micelegacy'])} legacy) from {commit}")
