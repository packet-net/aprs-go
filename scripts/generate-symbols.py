#!/usr/bin/env python3
"""Regenerates symbols.go: every symbol the APRS symbol tables define, by name.

Usage: scripts/generate-symbols.py <AprsSymbol.Named.cs>

The names and descriptions are packet.net's (src/Packet.Aprs/AprsSymbol.Named.cs in aprs-cs, from
the symbol table in APRS12c ch. 21 and APRS-Symbols), so the implementations name symbols alike;
each name gets a Symbol prefix here.
"""
import html, json, pathlib, re, sys

cs = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
pattern = re.compile(r"/// <summary>(.*?): <c>.*?</c>\.</summary>\s*\n\s*public static AprsSymbol (\w+) => new\('(\\\\|.)', '(\\.|.)'\);")
symbols = []
for m in pattern.finditer(cs):
    table = "\\" if m.group(3) == "\\\\" else m.group(3)
    code = m.group(4)[1:] if m.group(4).startswith("\\") else m.group(4)
    symbols.append((m.group(2), table, code, html.unescape(m.group(1))))
declared = cs.count("public static AprsSymbol ")
if declared != len(symbols):
    sys.exit(f"read {len(symbols)} symbols of {declared}")


def rune(c):
    return {"\\": "'\\\\'", "'": "'\\''"}.get(c, f"'{c}'")


lines = [
    "// Code generated by scripts/generate-symbols.py from aprs-cs's AprsSymbol.Named.cs. DO NOT EDIT.",
    "",
    "package aprs",
    "",
    "// Every symbol the APRS symbol tables define, by name (APRS12c ch. 21). The names match the other",
    "// implementations'.",
    "var (",
]
for name, table, code, description in symbols:
    lines.append(f"\t// Symbol{name} is {description}: {table}{code}.")
    lines.append(f"\tSymbol{name} = Symbol{{Table: {rune(table)}, Code: {rune(code)}}}")
lines += [")", "", "var symbolDescriptions = map[Symbol]string{"]
for name, table, code, description in symbols:
    lines.append(f"\tSymbol{name}: {json.dumps(description, ensure_ascii=False)},")
lines += ["}", ""]
dest = pathlib.Path(__file__).resolve().parent.parent / "symbols.go"
dest.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {dest} ({len(symbols)} symbols)")
